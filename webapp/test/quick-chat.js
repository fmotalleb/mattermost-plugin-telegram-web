const {dom, React, ReactDOM, container, store, state, tick, ok, report, payloads, holdPosts} = require('./harness');
const {setStore} = require('../src/mm/store');
const {initSettings, updateSettings} = require('../src/mm/settings');
const {saveComposerDraft, getComposerDraft} = require('../src/mm/drafts');
const {receivePost} = require('../src/mm/posts');
const {TelegramUI} = require('../src/ui/TelegramUI');
setStore(store);
initSettings();
updateSettings({mode: 'on'});
saveComposerDraft('channel-dm', 'saved before chat opened');
const root = ReactDOM.createRoot(container);
root.render(React.createElement(TelegramUI));
const wait = async (fn) => { for (let n = 0; n < 70 && !fn(); n++) await tick(30); return fn(); };
const fire = (node, type, button = 0) => node?.dispatchEvent(new dom.window.MouseEvent(type, {bubbles: true, cancelable: true, button}));
const type = async (node, value) => {
    Object.getOwnPropertyDescriptor(dom.window.HTMLTextAreaElement.prototype, 'value').set.call(node, value);
    node.dispatchEvent(new dom.window.Event('input', {bubbles: true}));
    await tick(50);
};
(async () => {
    await wait(() => document.querySelector('.tgw-chat-row'));
    const row = Array.from(document.querySelectorAll('.tgw-chat-row')).find((x) => x.textContent.includes('Alice'));
    fire(row, 'click');
    await wait(() => document.querySelector('.tgw-shell textarea'));
    const main = document.querySelector('.tgw-shell textarea');
    ok(main.value === 'saved before chat opened', 'opening chat loads a wrapped Mattermost draft');
    saveComposerDraft('channel-dm', 'draft hydrated after mount');
    await wait(() => main.value === 'draft hydrated after mount');
    ok(main.value === 'draft hydrated after mount', 'late host hydration updates composer');
    const town = Array.from(document.querySelectorAll('.tgw-chat-row')).find(x => x.textContent.includes('Town Square'));
    saveComposerDraft('channel-town', 'saved other chat');
    fire(town, 'click');
    await wait(() => document.querySelector('.tgw-shell textarea').value === 'saved other chat');
    ok(document.querySelector('.tgw-shell textarea').value === 'saved other chat', 'switching chats hydrates the destination draft');
    fire(row, 'click');
    await wait(() => main.value === 'draft hydrated after mount');
    ok(main.value === 'draft hydrated after mount', 'returning restores the original channel draft');
    await type(main, 'shared draft');
    ok(!!document.querySelector('.tgw-draft-preview')?.textContent.includes('shared draft'), 'saved draft appears in chat list');
    const url = dom.window.location.href;
    const mainTitle = document.querySelector('.tgw-shell .tgw-chat-header-title').textContent;
    fire(row, 'mousedown', 1);
    fire(row, 'auxclick', 1);
    await wait(() => document.querySelector('.tgw-quick-dialog textarea'));
    const modal = document.querySelector('.tgw-quick-dialog');
    ok(document.querySelectorAll('.tgw-quick-dialog').length === 1, 'middle click opens one modal');
    ok(dom.window.location.href === url && document.querySelector('.tgw-shell .tgw-chat-header-title').textContent === mainTitle, 'quick chat preserves route and main selection');
    const area = modal.querySelector('textarea');
    ok(area.value === 'shared draft', 'quick chat hydrates main draft');
    await type(area, 'updated together');
    ok(main.value === 'updated together', 'main composer follows quick chat draft');
    saveComposerDraft('channel-dm', 'host updated draft');
    await tick(80);
    ok(area.value === 'host updated draft' && main.value === area.value, 'both composers follow external draft updates');
    receivePost({id: 'quick-incoming', channel_id: 'channel-dm', user_id: 'user-alice', message: 'live quick message', create_at: Date.now(), update_at: Date.now(), props: {}});
    await wait(() => modal.textContent.includes('live quick message'));
    ok(modal.textContent.includes('live quick message'), 'live incoming messages reach quick chat');
    const release = holdPosts();
    await type(area, 'quick outgoing');
    fire(modal.querySelector('.tgw-send-button'), 'click');
    await tick(60);
    ok(main.value === '' && area.value === '', 'send clears shared draft immediately');
    await type(area, 'next draft');
    fire(modal.querySelector('[title="Close quick chat"]'), 'click');
    release();
    await tick(150);
    ok(!document.querySelector('.tgw-quick-dialog') && main.value === 'next draft', 'close during send preserves next shared draft');
    ok(payloads.some((x) => x.path === '/posts' && x.body.message === 'quick outgoing' && x.body.channel_id === 'channel-dm'), 'send keeps modal destination');
    fire(row, 'auxclick', 1);
    await wait(() => document.querySelector('.tgw-quick-dialog textarea'));
    ok(document.querySelector('.tgw-quick-dialog textarea').value === 'next draft', 'reopen retains shared draft');
    const {api} = require('../src/mm/api');
    const originalSend = api.createPost;
    api.createPost = async () => { throw new Error('test send failure'); };
    const reopened = document.querySelector('.tgw-quick-dialog');
    await type(reopened.querySelector('textarea'), 'restore after failure');
    fire(reopened.querySelector('.tgw-send-button'), 'click');
    await wait(() => reopened.querySelector('textarea').value === 'restore after failure');
    ok(main.value === 'restore after failure', 'failed send restores shared draft');
    api.createPost = originalSend;
    const originalUpload = api.uploadFile;
    api.uploadFile = async () => ({file_infos: [{id: 'quick-file', name: 'quick.txt', mime_type: 'text/plain', size: 4}]});
    const input = reopened.querySelector('input[type="file"]');
    Object.defineProperty(input, 'files', {configurable: true, value: [new dom.window.File(['test'], 'quick.txt', {type: 'text/plain'})]});
    input.dispatchEvent(new dom.window.Event('change', {bubbles: true}));
    await tick(100);
    fire(reopened.querySelector('.tgw-send-button'), 'click');
    await wait(() => payloads.some(x => x.path === '/posts' && x.body.file_ids?.includes('quick-file')));
    ok(payloads.some(x => x.path === '/posts' && x.body.file_ids?.includes('quick-file')), 'quick chat sends uploaded attachment');
    api.uploadFile = originalUpload;
    const {loadChannel, getBlock} = require('../src/mm/posts');
    const originalPosts = api.getPosts;
    api.getPosts = async () => { throw new Error('test history failure'); };
    await loadChannel('channel-dm', {force: true});
    await tick(60);
    ok(reopened.textContent.includes('Could not load messages.'), 'history failure displays retry');
    api.getPosts = originalPosts;
    const retry = Array.from(reopened.querySelectorAll('button')).find(x => x.textContent === 'Retry');
    fire(retry, 'click');
    await wait(() => !getBlock('channel-dm').error);
    ok(!getBlock('channel-dm').error, 'retry reloads history');
    const block = getBlock('channel-dm');
    block.hasMoreOlder = true;
    receivePost({...block.posts[block.order[0]], update_at: Date.now()});
    await tick(50);
    const older = Array.from(reopened.querySelectorAll('button')).find(x => x.textContent === 'Load earlier messages');
    ok(!!older, 'quick chat offers older history');
    if (older) fire(older, 'click');
    await tick(80);
    const image = reopened.querySelector('.tgw-attachment-image');
    if (image) {
        fire(image, 'click');
        await tick(50);
        ok(!!document.querySelector('.tgw-image-viewer'), 'quick chat opens image preview');
        document.dispatchEvent(new dom.window.KeyboardEvent('keydown', {key: 'Escape', bubbles: true}));
        await tick(50);
        ok(!!document.querySelector('.tgw-quick-dialog') && !document.querySelector('.tgw-image-viewer'), 'Escape dismisses image before chat');
    }
    document.dispatchEvent(new dom.window.KeyboardEvent('keydown', {key: 'Escape', bubbles: true}));
    await tick(50);
    ok(!document.querySelector('.tgw-quick-dialog'), 'Escape closes modal');
    ok(!document.querySelector('.tgw-shell').inert, 'closing restores background interaction');
    root.unmount();
    report('QUICK CHAT TEST');
})().catch((error) => { console.error(error); process.exitCode = 1; root.unmount(); });
