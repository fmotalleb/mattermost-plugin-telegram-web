const {React,ReactDOM,container,dom,tick,ok,report} = require('./harness');
const {deferred} = require('../src/ui/deferred');
const root = ReactDOM.createRoot(container);
const wait = async (predicate) => { for(let n=0;n<200&&!predicate();n++) await tick(20); return predicate(); };
let requests=0, resolve;
const View=deferred(()=>{requests++;return new Promise((done)=>{resolve=done;});},'test view');
(async()=>{
    ok(requests===0,'declaring an optional view does not load its code');
    root.render(React.createElement(View,{name:'Alice'}));await wait(()=>requests===1);
    ok(requests===1&&container.textContent.includes('Loading test view'),'mounting an optional view requests it and shows loading feedback');
    resolve(({name})=>React.createElement('span',null,`Hello ${name}`));await tick(30);
    ok(container.textContent==='Hello Alice','a loaded view receives its props');
    root.render(null);await tick(20);root.render(React.createElement(View,{name:'Bob'}));await tick(20);
    ok(requests===1&&container.textContent==='Hello Bob','reopening reuses the loaded module');
    let attempts=0;
    const Retry=deferred(()=>++attempts===1?Promise.reject(new Error('offline')):Promise.resolve(()=>React.createElement('span',null,'Recovered')),'retry view');
    root.render(React.createElement(Retry));await wait(()=>container.querySelector('[role="alert"]'));
    ok(container.querySelector('[role="alert"]')?.textContent.includes('Could not load'),'failed chunks show a recoverable error');
    container.querySelector('button').dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true}));await tick(30);
    ok(attempts===2&&container.textContent==='Recovered','Retry requests a failed chunk again');
    let complete;
    const Late=deferred(()=>new Promise((done)=>{complete=done;}),'late view');
    let cancelled=false;
    root.render(React.createElement(Late,{deferredCancel:()=>{cancelled=true;root.render(null);}}));await wait(()=>complete);
    document.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:'Escape',bubbles:true,cancelable:true}));await tick(20);
    ok(cancelled,'Escape cancels a pending view before its code arrives');
    root.render(null);await tick(20);
    complete(()=>React.createElement('span',null,'Late view'));await tick(20);
    ok(!container.textContent,'a view closed during loading does not appear later');
    root.unmount();report('DEFERRED VIEW TEST');
})().catch((error)=>{console.error(error);root.unmount();process.exitCode=1;});
