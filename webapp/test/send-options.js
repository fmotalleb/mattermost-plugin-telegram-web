const {dom, React, ReactDOM, container, store, state, tick, ok, report, payloads, ids} = require('./harness');
const {setStore} = require('../src/mm/store');
const {initSettings, updateSettings} = require('../src/mm/settings');
const {TelegramUI} = require('../src/ui/TelegramUI');
const {getComposerDraft} = require('../src/mm/drafts');
const originalFetch = global.fetch;
let rejectSchedule = false;
let holdSchedule;
const scheduled = [];
global.fetch = async (url, options = {}) => {
    if (new URL(url, 'https://mattermost.example.com').pathname.endsWith('/posts/schedule')) {
        const body = JSON.parse(options.body);
        scheduled.push(body);
        if (holdSchedule) await holdSchedule;
        const status = rejectSchedule ? 403 : 201;
        return {ok: status < 400, status, text: async () => JSON.stringify(rejectSchedule ? {message: 'Scheduling is unavailable'} : {...body, id: 'scheduled-one'})};
    }
    return originalFetch(url, options);
};
setStore(store);
initSettings();
updateSettings({mode: 'on'});
const root = ReactDOM.createRoot(container);
root.render(React.createElement(TelegramUI));
const wait = async (fn) => { for (let n = 0; n < 100 && !fn(); n++) await tick(25); return fn(); };
const click = (node) => node?.dispatchEvent(new dom.window.MouseEvent('click', {bubbles: true}));
const type = async (node, value, prototype = dom.window.HTMLTextAreaElement.prototype) => {
    Object.getOwnPropertyDescriptor(prototype, 'value').set.call(node, value);
    node.dispatchEvent(new dom.window.Event('input', {bubbles: true}));
    await tick(70);
};
const confirm = () => Array.from(document.querySelectorAll('.tgw-schedule-actions button')).find((button) => button.textContent === 'Schedule message');
(async () => {
    await wait(() => document.querySelector('.tgw-chat-row'));
    click(Array.from(document.querySelectorAll('.tgw-chat-row')).find((row) => row.textContent.includes('Alice')));
    await wait(() => document.querySelector('.tgw-composer textarea'));
    const area = document.querySelector('.tgw-composer textarea');
    const options = document.querySelector('.tgw-send-options');
    ok(options?.previousElementSibling?.title === 'Link', 'delivery options follow formatting controls in the toolbar');
    click(document.querySelector('.tgw-urgent-toggle'));
    await tick(60);
    await type(area, 'urgent now');
    click(document.querySelector('.tgw-send-button'));
    await wait(() => payloads.some((request) => request.path === '/posts' && request.body?.message === 'urgent now'));
    const urgent = payloads.find((request) => request.path === '/posts' && request.body?.message === 'urgent now');
    ok(urgent?.body.metadata?.priority?.priority === 'urgent', 'urgent messages use native priority metadata');
    await wait(() => document.querySelector('.tgw-msg-priority'));
    ok(document.querySelector('.tgw-msg-priority')?.textContent === 'Urgent', 'urgent message retains a visible label after server echo');
    ok(document.querySelector('.tgw-urgent-toggle').getAttribute('aria-pressed') === 'false', 'urgent selection resets after sending');
    await type(area, 'send later');
    click(document.querySelector('.tgw-urgent-toggle'));
    click(document.querySelector('.tgw-schedule-toggle'));
    await wait(() => document.querySelector('[aria-label="Scheduled send time"]'));
    const postsBefore = payloads.filter((request) => request.path === '/posts').length;
    click(confirm());
    await wait(() => scheduled.length === 1 && !document.querySelector('.tgw-schedule-panel'));
    ok(scheduled[0]?.message === 'send later' && scheduled[0]?.channel_id === ids.DM && scheduled[0]?.scheduled_at > Date.now(), 'schedule submits a future server-side post in the current channel');
    ok(scheduled[0]?.priority?.priority === 'urgent' && scheduled[0]?.priority?.requested_ack === false, 'scheduled urgency uses the scheduled-post priority field');
    ok(payloads.filter((request) => request.path === '/posts').length === postsBefore, 'scheduling never publishes an immediate post');
    ok(area.value === '' && !getComposerDraft(ids.DM)?.message, 'successful scheduling clears the draft');
    await type(area, 'invalid date draft');
    click(document.querySelector('.tgw-schedule-toggle'));
    await wait(() => document.querySelector('[aria-label="Scheduled send time"]'));
    await type(document.querySelector('[aria-label="Scheduled send time"]'), '2000-01-01T12:00', dom.window.HTMLInputElement.prototype);
    click(confirm());
    await wait(() => document.querySelector('.tgw-schedule-error'));
    ok(scheduled.length === 1 && area.value === 'invalid date draft', 'past dates are rejected without clearing the message');
    click(document.querySelector('.tgw-schedule-actions button'));
    await type(area, 'retry scheduling');
    rejectSchedule = true;
    click(document.querySelector('.tgw-urgent-toggle'));
    click(document.querySelector('.tgw-schedule-toggle'));
    await wait(() => confirm());
    click(confirm());
    await wait(() => Array.from(document.querySelectorAll('.tgw-toast')).some((toast) => toast.textContent.includes('Scheduling is unavailable')) && area.value === 'retry scheduling' && !document.querySelector('.tgw-schedule-toggle').disabled);
    ok(area.value === 'retry scheduling' && document.querySelector('.tgw-urgent-toggle').getAttribute('aria-pressed') === 'true', 'server rejection restores message and urgent priority');
    ok(!!document.querySelector('.tgw-schedule-panel'), 'server rejection leaves the date picker available to retry');
    rejectSchedule = false;
    click(confirm());
    await wait(() => !document.querySelector('.tgw-schedule-panel'));
    ok(scheduled.length === 3 && area.value === '', 'retry schedules the restored message');
    await type(area, '/help topic');
    click(document.querySelector('.tgw-schedule-toggle'));
    await wait(() => confirm());
    click(confirm());
    await tick(90);
    ok(scheduled.length === 3 && area.value === '/help topic', 'slash commands cannot be scheduled');
    click(document.querySelector('.tgw-schedule-actions button'));
    await type(area, 'scheduled attachment');
    const input = document.querySelector('.tgw-composer input[type="file"]');
    Object.defineProperty(input, 'files', {configurable: true, value: [new dom.window.File(['test'], 'note.txt', {type: 'text/plain'})]});
    input.dispatchEvent(new dom.window.Event('change', {bubbles: true}));
    await wait(() => document.querySelector('.tgw-attachment-chip-size')?.textContent !== 'Uploading…');
    click(document.querySelector('.tgw-schedule-toggle'));
    await wait(() => confirm() && !confirm().disabled);
    click(confirm());
    await wait(() => scheduled.length === 4);
    ok(scheduled[3]?.file_ids?.length === 1, 'scheduled posts include uploaded attachments');
    await wait(() => !document.querySelector('.tgw-schedule-panel'));
    const replyButton = document.querySelector('.tgw-msg-toolbar button[title="Reply"]');
    click(replyButton);
    await wait(() => document.querySelector('.tgw-reply-bar'));
    ok(document.querySelector('.tgw-urgent-toggle').disabled, 'reply composer disables unsupported urgent priority');
    await type(area, 'scheduled reply');
    click(document.querySelector('.tgw-schedule-toggle'));
    await wait(() => confirm());
    let release;
    holdSchedule = new Promise((resolve) => { release = resolve; });
    click(confirm());
    await wait(() => scheduled.length === 5);
    ok(!!scheduled[4]?.root_id && !scheduled[4]?.priority, 'scheduled replies retain thread context');
    await type(area, 'next draft');
    release(); holdSchedule = null;
    await wait(() => !document.querySelector('.tgw-schedule-panel'));
    ok(area.value === 'next draft', 'late scheduling completion preserves the next draft');
    root.unmount();
    report('SEND OPTIONS TEST');
})().catch((error) => { console.error(error); root.unmount(); process.exitCode = 1; });
