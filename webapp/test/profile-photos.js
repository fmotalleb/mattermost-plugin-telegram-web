const {dom, React, ReactDOM, container, store, state, tick, ok, report, ids, payloads} = require('./harness');
const {setStore} = require('../src/mm/store');
const {initSettings, updateSettings} = require('../src/mm/settings');
const {TelegramUI} = require('../src/ui/TelegramUI');
const {Avatar} = require('../src/ui/primitives');
setStore(store); initSettings(); updateSettings({mode:'on'});
const root=ReactDOM.createRoot(container); root.render(React.createElement(TelegramUI));
const wait=async(fn)=>{for(let n=0;n<100&&!fn();n++)await tick(25);return fn();};
const click=(node)=>node?.dispatchEvent(new dom.window.MouseEvent('click',{bubbles:true,cancelable:true}));
const key=async(node,value)=>{node.dispatchEvent(new dom.window.KeyboardEvent('keydown',{key:value,bubbles:true,cancelable:true}));await tick(60);};
const viewer=()=>document.querySelector('[aria-label="User profile"]');
const close=async()=>{click(viewer()?.querySelector('[title="Close"]'));await wait(()=>!viewer());};
(async()=>{
    await wait(()=>document.querySelector('.tgw-chat-header-main .tgw-avatar img') && document.activeElement === document.querySelector('.tgw-composer textarea'));
    const trigger=document.querySelector('.tgw-chat-header-main .tgw-avatar img');
    const title=document.querySelector('.tgw-chat-header-title').textContent;
    const requestsBefore=payloads.length;
    click(trigger);await wait(viewer);
    ok(viewer()?.getAttribute('role')==='dialog'&&viewer()?.getAttribute('aria-modal')==='true','profile picture click opens the user profile modal');
    ok(viewer()?.querySelector('img')?.src===trigger.src && viewer()?.textContent.includes('Open direct chat')&&viewer()?.textContent.includes('Alice'),'viewer shows the selected picture and its name');
    ok(!document.querySelector('.tgw-info-panel')&&document.querySelector('.tgw-chat-header-title').textContent===title,'photo click does not open chat info or change chats');
    ok(document.activeElement===viewer()?.querySelector('button'),'viewer focuses its close control');
    await key(document.activeElement,'Tab');
    ok(document.activeElement?.textContent==='Open direct chat','Tab reaches the direct chat action');
    await key(document.activeElement,'Tab');
    ok(document.activeElement===viewer()?.querySelector('button'),'Tab stays within the profile modal');
    await key(document.activeElement,'Escape');await wait(()=>!viewer());
    ok(!viewer()&&document.activeElement===trigger,'Escape closes the viewer and restores focus to the photo');
    await key(trigger,'Enter');await wait(viewer);ok(!!viewer(),'keyboard Enter opens a profile picture');await close();
    await key(trigger,' ');await wait(viewer);ok(!!viewer(),'keyboard Space opens a profile picture');
    viewer().parentElement.dispatchEvent(new dom.window.MouseEvent('mousedown',{bubbles:true}));await wait(()=>!viewer());
    ok(!viewer(),'clicking the backdrop closes the viewer');
    const rowPhoto=document.querySelector('.tgw-sidebar .tgw-chat-row .tgw-avatar img');
    click(rowPhoto);await wait(viewer);
    ok(!!viewer()&&document.querySelector('.tgw-chat-header-title').textContent===title,'sidebar photo opens the viewer without activating its chat row');await close();
    ok(!payloads.slice(requestsBefore).some((request)=>request.path==='/channels/direct'),'viewing photos never creates a direct channel');
    const row=Array.from(document.querySelectorAll('.tgw-chat-row')).find((node)=>node.textContent.includes('Alice'));
    row.dispatchEvent(new dom.window.MouseEvent('auxclick',{button:1,bubbles:true}));
    await wait(()=>document.querySelector('.tgw-quick-dialog .tgw-avatar img'));
    click(document.querySelector('.tgw-quick-dialog .tgw-chat-header-main .tgw-avatar img'));await wait(viewer);
    ok(!!viewer(),'quick chat can open a profile photo');
    await key(document,'Escape');await wait(()=>!viewer());
    ok(!viewer()&&!!document.querySelector('.tgw-quick-dialog'),'Escape closes only the photo viewer above a quick chat');
    click(document.querySelector('.tgw-quick-close'));await wait(()=>!document.querySelector('.tgw-quick-dialog'));
    // The info panel can enlarge its participant picture without closing itself.
    click(document.querySelector('.tgw-chat-header-title'));
    await wait(()=>document.querySelector('.tgw-info-panel'));
    const profilePhoto=document.querySelector('.tgw-info-panel .tgw-avatar img');
    click(profilePhoto);await wait(viewer);
    ok(!!viewer()?.textContent.includes('Open direct chat'),'info panel photo opens the same profile card with a direct chat action');
    const cardPhoto=viewer().querySelector('img');
    click(cardPhoto);await tick(50);
    ok(document.querySelectorAll('[aria-label="User profile"]').length===1 && !cardPhoto.hasAttribute('role'),'profile card photo does not open a nested modal');
    await close();ok(!!document.querySelector('.tgw-info-panel'),'closing the profile preserves the info panel');
    root.unmount();
    const probe=document.createElement('div');document.body.appendChild(probe);const probeRoot=ReactDOM.createRoot(probe);
    const photoProps={userId:ids.OTHER,name:'Alice',profile:state.entities.users.profiles[ids.OTHER]};
    probeRoot.render(React.createElement(Avatar,photoProps));await wait(()=>probe.querySelector('img'));
    probe.querySelector('img').dispatchEvent(new dom.window.Event('error',{bubbles:false}));await wait(()=>!probe.querySelector('img'));
    ok(!probe.querySelector('img')&&!!probe.querySelector('.tgw-avatar-initials'),'failed thumbnail falls back to initials');
    probeRoot.render(React.createElement(Avatar,{...photoProps,userId:'another-user',profile:{id:'another-user',username:'another',last_picture_update:99}}));
    await wait(()=>probe.querySelector('img'));
    ok(probe.querySelector('img')?.src.includes('/users/another-user/image'),'a different user picture retries after a previous thumbnail failed');
    probeRoot.unmount();probe.remove();
    report('PROFILE PHOTO TEST');
})().catch((error)=>{console.error(error);root.unmount();process.exitCode=1;});
